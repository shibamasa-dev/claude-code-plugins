#!/bin/bash
# =============================================================================
# environment-setup.sh — 環境層(VM プロビジョニング・重い導入・初回のみ)
# remote-setup スキルが生成。このファイルは「リポジトリにコミットするだけでは動かない」。
# claude.ai/code → 環境ダイアログ → Setup script 欄に【この内容を丸ごと貼り付けて】有効化する。
#
# 仕様(公式): 新規クラウドセッション開始時・Claude Code 起動前に root で実行され、
# 完了後のファイルシステムがスナップショットされ約7日キャッシュされる(以後スキップ)。
# Setup script かネットワーク設定を変更するとキャッシュは再構築される。
#
# 制約:
# - リポジトリはまだ無い前提で書く(自己完結・固定パスにインストールする)
# - 約5分以内 / 終了コード 0 必須(重要でないステップは `|| true`)
