# --- ▼▼▼ リポジトリ固有の重量級インストール(生成時にここを書き換える) ▼▼▼ ---
# ここに置くもの: apt パッケージ / グローバル CLI / system pip への重量パッケージ /
# 事前ビルド済みバイナリの取得。リポ非依存の固定パスへ入れること。
#
# 例(apt): apt-get install -y -qq libgl1 libglu1-mesa || true
# 例(グローバル CLI): npm install -g @google/clasp || true
# 例(重量 Python パッケージを system へ。セッション層の venv からは
#     --system-site-packages で見える):
#   pip install --break-system-packages build123d || true
# --- ▲▲▲ リポジトリ固有ステップここまで ▲▲▲ ---------------------------------

exit 0
