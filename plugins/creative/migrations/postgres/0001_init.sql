-- Image history schema, Postgres dialect (Postgres 13+, Supabase). migrations/sqlite/0001_init.sql is the same schema for SQLite.
--
-- Runs on its own, without the bundled MCP server: the server applies it when it first opens database_url,
-- and over a connector Claude sends the whole file to the connector's migration tool (Supabase: apply_migration).
-- Safe to run more than once: IF NOT EXISTS, CREATE OR REPLACE, DROP TRIGGER IF EXISTS, ON CONFLICT DO NOTHING.
-- Objects go to the first schema on search_path (public on Supabase), hence the img_ prefix.
--
-- Never edit a file that has shipped: CREATE TABLE IF NOT EXISTS skips a table that exists, and the version is already
-- recorded. A later change goes in a new file (0002_<name>.sql) that alters what exists, for example ADD COLUMN.
--
-- Don't write BEGIN, COMMIT or ROLLBACK in a migration file (this one or any later one): the server runs
-- each file inside its own transaction, so it applies completely or not at all.
--
-- Timestamps are UTC text with milliseconds, the same format as SQLite: 2026-11-23T09:30:00.123Z

-- The same img_norm() the MCP server registers on SQLite. Search with: search_text LIKE '%' || img_norm('<term>') || '%'
CREATE OR REPLACE FUNCTION img_norm(text) RETURNS text
  LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
  AS $$ SELECT lower(normalize($1, NFKC)) $$;

CREATE OR REPLACE FUNCTION img_now() RETURNS text
  LANGUAGE sql VOLATILE
  AS $$ SELECT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"') $$;

CREATE TABLE IF NOT EXISTS img_schema_migrations (
  version    text PRIMARY KEY,
  applied_at text NOT NULL DEFAULT img_now()
);

-- One row per image attempt: a plan, a generated image, a rejected draft, a variant or an edit.
-- A refinement is a new row whose based_on names the attempt it builds on; rows are not overwritten.
CREATE TABLE IF NOT EXISTS img_attempts (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title        text NOT NULL CHECK (title <> ''),
  request      text NOT NULL,                -- the user's request, in their words, or a summary of it
  asset_type   text,                         -- '16:9 banner', 'app icon', 'hero image'
  style        text,                         -- rendering and taste
  composition  text,                         -- layout and reading order
  prompt       text,                         -- the final prompt (the five-section structure)
  route        text,                         -- the route id that generated it (codex, gemini, openai, fal, ...); NULL for a plan only
  output_paths jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(output_paths) = 'array'),
  based_on     bigint REFERENCES img_attempts (id),
  -- What this attempt reused from earlier references or attempts
  reuse_scope  text CHECK (reuse_scope IN ('composition_only', 'style_only', 'palette_only', 'typography_only',
                                           'subject_only', 'full_reference', 'none')),
  tags         text,                         -- comma-separated
  notes        text,                         -- feedback, failure notes, the reuse decision, IP-safety notes
  status       text NOT NULL DEFAULT 'planned'
               CHECK (status IN ('planned', 'generated', 'accepted', 'rejected', 'failed', 'superseded')),
  search_text  text,                         -- img_norm() of the text columns, maintained by a trigger
  created_at   text NOT NULL DEFAULT img_now(),
  updated_at   text NOT NULL DEFAULT img_now()
);
CREATE INDEX IF NOT EXISTS img_attempts_created_ix ON img_attempts (created_at);

-- A reference image attached to an attempt, kept as a compact proxy under the plugin data directory.
-- role says what a later generation may borrow from it.
CREATE TABLE IF NOT EXISTS img_references (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id    bigint NOT NULL REFERENCES img_attempts (id) ON DELETE CASCADE,
  role          text NOT NULL DEFAULT 'full_reference'
                CHECK (role IN ('composition_only', 'style_only', 'palette_only', 'typography_only',
                                'subject_only', 'full_reference', 'none')),
  label         text,
  source_path   text NOT NULL,               -- where the original was, for provenance; never copied
  source_sha256 text NOT NULL CHECK (length(source_sha256) = 64),
  source_bytes  bigint NOT NULL CHECK (source_bytes >= 0),
  proxy_ref     text,                        -- file name in the proxy folder; NULL when only notes are kept
  proxy_bytes   bigint CHECK (proxy_bytes >= 0),
  width         integer CHECK (width >= 0),
  height        integer CHECK (height >= 0),
  max_edge      integer CHECK (max_edge > 0),
  format        text,
  notes         text,
  created_at    text NOT NULL DEFAULT img_now(),
  updated_at    text NOT NULL DEFAULT img_now(),
  UNIQUE (attempt_id, source_sha256)
);
CREATE INDEX IF NOT EXISTS img_references_role_ix ON img_references (role, attempt_id);

-- Triggers

CREATE OR REPLACE FUNCTION img_set_updated_at() RETURNS trigger
  LANGUAGE plpgsql
  AS $$ BEGIN NEW.updated_at := img_now(); RETURN NEW; END $$;

CREATE OR REPLACE FUNCTION img_attempts_set_search_text() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
BEGIN
  NEW.search_text := img_norm(NEW.title || ' ' || NEW.request || ' ' || coalesce(NEW.asset_type, '') || ' '
                              || coalesce(NEW.style, '') || ' ' || coalesce(NEW.composition, '') || ' '
                              || coalesce(NEW.prompt, '') || ' ' || coalesce(NEW.tags, '') || ' '
                              || coalesce(NEW.notes, ''));
  RETURN NEW;
END $$;

-- An id is the row's identity: other rows and notes refer to it
CREATE OR REPLACE FUNCTION img_reject_id_change() RETURNS trigger
  LANGUAGE plpgsql
  AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id THEN
    RAISE EXCEPTION '%.id cannot change; insert a new row instead', TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS img_attempts_search_text ON img_attempts;
CREATE TRIGGER img_attempts_search_text BEFORE INSERT OR UPDATE ON img_attempts
  FOR EACH ROW EXECUTE FUNCTION img_attempts_set_search_text();

DROP TRIGGER IF EXISTS img_attempts_updated_at ON img_attempts;
CREATE TRIGGER img_attempts_updated_at BEFORE UPDATE ON img_attempts
  FOR EACH ROW EXECUTE FUNCTION img_set_updated_at();

DROP TRIGGER IF EXISTS img_references_updated_at ON img_references;
CREATE TRIGGER img_references_updated_at BEFORE UPDATE ON img_references
  FOR EACH ROW EXECUTE FUNCTION img_set_updated_at();

DROP TRIGGER IF EXISTS img_attempts_id_immutable ON img_attempts;
CREATE TRIGGER img_attempts_id_immutable BEFORE UPDATE OF id ON img_attempts
  FOR EACH ROW EXECUTE FUNCTION img_reject_id_change();

DROP TRIGGER IF EXISTS img_references_id_immutable ON img_references;
CREATE TRIGGER img_references_id_immutable BEFORE UPDATE OF id ON img_references
  FOR EACH ROW EXECUTE FUNCTION img_reject_id_change();

-- Search entry point: one row per attempt, with the roles of its references (comma-separated)
CREATE OR REPLACE VIEW img_v_attempts AS
SELECT a.id, a.created_at, a.status, a.title, a.asset_type, a.style, a.composition, a.route, a.reuse_scope,
       a.based_on, a.tags, a.output_paths, a.notes, a.search_text, a.updated_at,
       (SELECT string_agg(DISTINCT r.role, ',' ORDER BY r.role) FROM img_references r
         WHERE r.attempt_id = a.id) AS reference_roles
  FROM img_attempts a;

-- Row level security on, with no policies: only the table owner (the direct connection or the connector) sees rows.
ALTER TABLE img_schema_migrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE img_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE img_references ENABLE ROW LEVEL SECURITY;

-- Views run with their owner's rights and would bypass RLS. On Supabase, new objects in public are granted to
-- the API roles anon and authenticated by default, so take the view away from them where those roles exist.
DO $$
DECLARE r text;
BEGIN
  FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
      EXECUTE format('REVOKE ALL ON img_v_attempts FROM %I', r);
    END IF;
  END LOOP;
END $$;

